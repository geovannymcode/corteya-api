#!/bin/sh
set -eu
: "${CORTEYA_OWNER_PASSWORD:?Define CORTEYA_OWNER_PASSWORD}"
: "${CORTEYA_APP_PASSWORD:?Define CORTEYA_APP_PASSWORD}"
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 --set=database="$POSTGRES_DB" <<'SQL'
\getenv owner_password CORTEYA_OWNER_PASSWORD
\getenv app_password CORTEYA_APP_PASSWORD
CREATE ROLE corteya_owner LOGIN PASSWORD :'owner_password' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION NOINHERIT;
CREATE ROLE corteya_app LOGIN PASSWORD :'app_password' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION NOINHERIT;
ALTER DATABASE :"database" OWNER TO corteya_owner;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO corteya_owner;
GRANT USAGE ON SCHEMA public TO corteya_app;
GRANT CONNECT ON DATABASE :"database" TO corteya_app;
ALTER DEFAULT PRIVILEGES FOR ROLE corteya_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO corteya_app;
ALTER DEFAULT PRIVILEGES FOR ROLE corteya_owner IN SCHEMA public GRANT USAGE ON SEQUENCES TO corteya_app;
SQL
